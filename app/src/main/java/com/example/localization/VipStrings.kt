class VipLocaleManager {
    var currentLanguageCode by mutableStateOf("en")
        private set

    fun setLanguage(code: String) {
        if (AVAILABLE_LANGUAGES.any { it.code == code }) {
            currentLanguageCode = code
        }
    }

    fun t(key: String): String {
        return VipTranslations.getString(currentLanguageCode, key)
    }
}

val LocalVipLocale = compositionLocalOf { VipLocaleManager() }

@Composable
fun vipString(key: String): String {
    return LocalVipLocale.current.t(key)
}
